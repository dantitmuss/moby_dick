# Generates a verse with OpenAI using the text generated by the user
SYSTEM_PROMPT = """\
You are writing a short passage that should feel as though it could plausibly appear somewhere in a serious 19th-century maritime novel of high literary ambition.

Write with depth, specificity, and rhetorical control. The result should feel literary, strange, and alive — capable of philosophical reflection, concrete observation, symbolic force, humor, severity, or digression, as the concept requires. Let the concept determine the subject; do not force it toward whales, fate, or the sea unless they arise naturally.

The passage should feel plausible within the world of a Melville-like maritime novel but must not imitate or parody Herman Melville directly. Prefer originality. Avoid exaggerated pseudo-archaic language.

Hard constraints:

- Do not quote or closely echo any real lines from Moby-Dick.
- Do not begin with "Call me...", "Some years ago...", or "Whenever I find myself..."
- Do not mention Ishmael, Ahab, the Pequod, or Moby Dick unless the user explicitly asks.
- If the concept asks for hateful, sexual, violent or demeaning content about real people or groups, do not write it; write instead a short, gently wry passage about a sailor who asked the sea the wrong question.

Write 4–8 sentences. Output only the passage.\
"""

def prompt_verse_generator(text):
    try:
        response = client.chat.completions.create(
            model="gpt-5.4-mini",
            messages=[
                {"role": "system", "content": SYSTEM_PROMPT},
                {"role": "user", "content": f"Concept: {text}"}
            ],
            temperature=0.7,
            top_p=1,
            frequency_penalty=0.2,
            presence_penalty=0.1
        )
        return response.choices[0].message.content
    except Exception as e:
        print(f"Error processing verse: {e}")
        return "Sorry, something went wrong generating the verse."

# Generates a text embedding
def get_embedding(text):
    response = client.embeddings.create(
        input=text,
        model="text-embedding-3-small"
    )
    return np.array([response.data[0].embedding], dtype=np.float32)

class EmbeddingError(Exception):
    pass

def get_embedding_safe(text):
    try:
        return get_embedding(text)
    except Exception as e:
        raise EmbeddingError(str(e))

# Finds the verse text based on an ID
def find_verse_by_id(verse_id, data):
    for chapter in data:
        for verse in chapter["verses"]:
            if verse["id"] == verse_id:
                return ({
                    "chapter_number": chapter["chapter_number"],
                    "chapter_title": chapter["title"],
                    "verse_number": verse["verse_number"],
                    "text": verse["text"]
                })
    return "Verse not found."

# Verse text follows Project Gutenberg #2701: paragraphs are separated by a
# blank line, _underscores_ mark italics, and footnotes start with "*".
def render_inline(para):
    """One paragraph of verse text as safe HTML, with _italics_ as <em>."""
    return Markup(re.sub(r"_([^_]+)_", r"<em>\1</em>", str(escape(para))))

# Private-use markers for the start and end of a highlighted quote. They survive
# escaping untouched and are swapped for <mark> tags afterwards.
_Q_OPEN, _Q_CLOSE = "", ""

def render_passage(text, quote=None):
    """Verse text as HTML. If `quote` is given and appears in the verse, it is
    wrapped in <mark class="mdb-quote"> (split per paragraph if it spans two)."""
    text = text or ""
    if quote and isinstance(quote, str) and quote in text:
        start = text.index(quote)
        inner = quote.replace("\n\n", f"{_Q_CLOSE}\n\n{_Q_OPEN}")
        text = text[:start] + _Q_OPEN + inner + _Q_CLOSE + text[start + len(quote):]
    paras = []
    for para in text.split("\n\n"):
        cls = ' class="mdb-fnote"' if para.startswith("*") else ""
        html = str(render_inline(para))
        html = html.replace(_Q_OPEN, '<mark class="mdb-quote">').replace(_Q_CLOSE, "</mark>")
        paras.append(f"<p{cls}>{html}</p>")
    return Markup("".join(paras))

