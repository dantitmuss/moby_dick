@app.route('/search', methods=['POST'])
@limiter.limit("10 per minute")
def search():
    query = request.form['query']

    # Step 1: Generate fake Melville-style verse
    generated_verse = prompt_verse_generator(query)

    # Step 2: Embed the generated verse
    try:
        query_embedding = get_embedding_safe(generated_verse)
    except EmbeddingError:
        return render_template('home.html', error="The search service is temporarily unavailable. Please try again later."), 503

    # Step 3: Search FAISS for the closest match
    D, I = index.search(query_embedding, k=3)

    matches = []
    for idx in I[0]:
        match_id = id_data[idx]  # Get the corresponding ID from the FAISS index
        verse = find_verse_by_id(match_id, moby_dick_data)  # Get the verse text
        matches.append(verse)  # Store it

    # Step 4: Return results
    return render_template('results.html',
                           query=query,
                           generated_verse=generated_verse,
                           matched_verses=matches)

def tag_matches(category, tag):
    """Verses carrying `tag` in `category`, or in any category when category is 'all'."""
    found, want = [], tag.strip().lower()
    for chapter in moby_dick_data:
        for verse in chapter["verses"]:
            tags = verse["open_ai_tags"]
            pool = [t for ts in tags.values() for t in ts] if category == "all" else tags.get(category, [])
            if want in (t.strip().lower() for t in pool):
                found.append({
                    "chapter_number": chapter["chapter_number"],
                    "chapter_title": chapter["title"],
                    "verse_number": verse["verse_number"],
                    "text": verse["text"]
                })
    return found

def render_tag_results(category, tag):
    pretty_category = "All marks" if category == "all" else display_names.get(category, category.replace("_", " ").title())
    if category == "all":
        key = tag.strip().lower()
        tag = next((TAG_CASING[(c, key)] for c in TAG_ORDER if (c, key) in TAG_CASING), tag)
    return render_template('tag-results.html',
                           category=pretty_category,
                           tag=tag,
                           found_texts=tag_matches(category, tag))

